function Locale:GetLang()
    if WorldExplorerCharDB and WorldExplorerCharDB.lang then
        return WorldExplorerCharDB.lang
    end
    local clientLocale = GetLocale and GetLocale() or "enUS"
    if clientLocale == "ukUA" then
        return "ukUA"
    end
    return "enUS"
end

function Locale:SetLang(lang)
    if lang ~= "ukUA" and lang ~= "enUS" then
        local cur = self:GetLang()
        lang = (cur == "ukUA") and "enUS" or "ukUA"
    end
    WorldExplorerCharDB.lang = lang
    return lang
end

function Locale:Get(key)
    local lang = self:GetLang()
    local dict = Strings[lang] or Strings.enUS
    if dict[key] ~= nil then
        return dict[key]
    end
    return Strings.enUS[key] or key
end

function WE:L(key)
    return Locale:Get(key)
end
